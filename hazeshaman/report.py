OUT = "docs/analysis"


def _model(path="docs/model.js"):
    return json.loads(open(path, encoding="utf-8").read().split("=", 1)[1].rstrip().rstrip(";"))


def _pct(x, d=0): return "–" if x is None else f"{x * 100:.{d}f}%"
def _n(x): return f"{int(x):,}"
def _hl(h): return f"{h % 12 or 12} {'AM' if h < 12 else 'PM'}"


def _table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def _write(name, text):
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name), "w", encoding="utf-8") as f: f.write(text.rstrip() + "\n")


def cost_matrix(m, cfns=(2, 4, 8, 16, 30), lams=(0, 0.25, 0.5, 1, 2, 5)):
    """Best announcement hour for each (miss cost, lateness cost) pair - same rule as the dashboard."""
    ah = m["announce_hours"]; res = {}
    for cfn in cfns:
        for lam in lams:
            best = None
            for H in ah:
                b = m["backtest"][str(H)]; n, pos = b["n"], b["pos"]
                if not pos: continue
                cands = [{"t": 0, "fn": 0, "fp": n - pos}, *b["grid"], {"t": 1.01, "fn": pos, "fp": 0}]
                rel, t = min(((cfn * c["fn"] + c["fp"]) / (cfn * pos), c["t"]) for c in cands)
                tot = rel + lam / 100 * (H - ah[0])
                if best is None or tot < best[0]: best = (tot, H, t, rel)
            res[(cfn, lam)] = best
    return res


